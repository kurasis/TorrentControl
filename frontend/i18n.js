let current = systemLocale();

function systemLocale() {
  return (navigator.language || "en").toLowerCase().startsWith("ru") ? "ru" : "en";
}

export function setLocale(preference) {
  current = preference === "en" || preference === "ru" ? preference : systemLocale();
  document.documentElement.lang = current;
}

export function locale() {
  return current;
}

export function has(key) {
  return key in strings.en;
}

// Looks up `key` and substitutes {name} parameters. The result is plain text.
export function t(key, params = {}) {
  const template = strings[current][key] ?? strings.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (name in params ? String(params[name]) : `{${name}}`));
}

// Applies translations as text content and attributes only; strings are never
// parsed as HTML.
export function applyTranslations(root = document) {
  document.documentElement.lang = current;
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll("[data-i18n-label]")) el.setAttribute("aria-label", t(el.dataset.i18nLabel));
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
}
